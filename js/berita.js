document.addEventListener('DOMContentLoaded', () => {
    const grid = document.getElementById('berita-grid');
    const sortSelect = document.getElementById('sort-select');
    const countText = document.getElementById('news-count');

    if (!grid) return;

    function renderNews(sortOrder = 'terbaru') {
        grid.innerHTML = '';
        
        let sorted = [...newsData];
        if (sortOrder === 'terbaru') {
            sorted.sort((a, b) => new Date(b.date) - new Date(a.date));
        } else {
            sorted.sort((a, b) => new Date(a.date) - new Date(b.date));
        }

        if (countText) countText.innerText = sorted.length;

        sorted.forEach(news => {
            const card = document.createElement('article');
            card.className = 'news-card';
            card.innerHTML = `
                <div class="news-img">
                    <img src="${news.image}" alt="${news.title}" loading="lazy">
                    <span class="news-cat">${news.category}</span>
                </div>
                <div class="news-body">
                    <div class="news-meta">
                        <span><i class='bx bx-calendar'></i> ${news.dateFormatted}</span>
                        <span><i class='bx bx-user'></i> ${news.author}</span>
                    </div>
                    <h3>${news.title}</h3>
                    <p>${news.desc}</p>
                    <a href="berita-detail.html?id=${news.id}" class="read-more">Baca Selengkapnya <i class='bx bx-right-arrow-alt'></i></a>
                </div>
            `;
            grid.appendChild(card);
        });
    }

    // Initial render
    renderNews('terbaru');

    // Handle sorting
    if (sortSelect) {
        sortSelect.addEventListener('change', (e) => {
            renderNews(e.target.value);
        });
    }
});
